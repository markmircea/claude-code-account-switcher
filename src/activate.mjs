// Phase 5: make the gateway the thing Claude Code actually talks to, and make it reversible.
//
// D-6 is the whole design: real *user-scope* environment variables, because the VS Code extension
// runs its own bundled claude.exe (useTerminal defaults to false) and a shell alias would cover the
// terminal but not the extension. User-scope vars cover both.
//
// The cost of that choice, stated plainly:
//   * ANTHROPIC_BASE_URL at user scope affects EVERY process this user starts, not just Claude
//     Code. Any other Anthropic SDK script on this machine will route through the gateway too.
//   * If the gateway is not running, Claude Code cannot reach the API at all. So activation also
//     installs a logon startup entry, and `doctor` is the first thing to reach for when anything
//     looks broken.
//   * Already-running processes (VS Code, terminals) keep the OLD environment. Activation prints
//     that reminder because it is the #1 "it didn't work" cause.

import { execFileSync, spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
import { loadConfig, pool, readAccountState, availability, CONFIG_PATH, PID_PATH, LOG_PATH } from './config.mjs';
import { resolveBearer, describeIdentity } from './creds.mjs';

const CLAUDE_HOME = process.env.CLAUDE_CONFIG_DIR || path.join(process.env.USERPROFILE || process.env.HOME || '', '.claude');

// Supported mode: the local secret travels in a HEADER, and ANTHROPIC_AUTH_TOKEN is deliberately
// NOT set. That variable is a "gateway credential" as far as Claude Code is concerned, and while it
// is set the client treats itself as a billed-API session and turns off its own "wait for the
// claude.ai usage limit to reset, then continue the task" feature - the thing that keeps overnight
// chats alive. With only ANTHROPIC_BASE_URL set, the client keeps authenticating to us with its
// saved claude.ai login (proved on 2.1.305: its own OAuth bearer + anthropic-beta oauth-2025-04-20),
// and claude-gw still re-signs /v1/messages with B or C.
export const GW_VARS = ['CLAUDE_CODE_USE_GATEWAY', 'ANTHROPIC_BASE_URL', 'ANTHROPIC_CUSTOM_HEADERS'];
// Rollback path: the old three-variable model. Works, just without auto-resume at the limit.
export const LEGACY_VARS = ['CLAUDE_CODE_USE_GATEWAY', 'ANTHROPIC_BASE_URL', 'ANTHROPIC_AUTH_TOKEN'];
export const ALL_VARS = [...new Set([...GW_VARS, ...LEGACY_VARS])];
export const SECRET_HEADER = 'x-gw-secret';

function ps(script) {
  // PowerShell 5.1, no profile. Values passed in are generated by us (hex secret, loopback URL) and
  // validated by setUserVar's guard, so inlining them is safe; secrets never travel in argv here
  // because these names/values are not sensitive beyond the local gateway secret.
  return execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 30000 }).trim();
}

export function readUserVar(name) {
  try { return ps(`[Environment]::GetEnvironmentVariable('${name}','User')`) || null; } catch { return null; }
}

export function setUserVar(name, value) {
  // ANTHROPIC_CUSTOM_HEADERS legitimately contains "x-gw-secret: <hex>" - a space and a colon - so
  // the guard allows those and still refuses anything that could break out of the PowerShell literal.
  if (value !== null && !/^[\w:/.\-, ]+$/.test(String(value))) {
    throw new Error(`refusing to write suspicious env value for ${name}`);
  }
  if (value !== null && /["'`&|<>^%$\\]/.test(String(value))) {
    throw new Error(`refusing to write env value with shell metacharacters for ${name}`);
  }
  const v = value === null ? '$null' : `'${value}'`;
  ps(`[Environment]::SetEnvironmentVariable('${name}', ${v}, 'User')`);
}

// Claude Code applies this `env` block to its OWN process, whichever process launched it - which
// user-scope variables cannot do for an already-running VS Code. Proven live on 2.1.305: with these
// keys in settings.json, "Developer: Reload Window" was enough to move the extension's session into
// subscription mode, so the #1 "it didn't work" cause (fully quit VS Code) stops being required.
// ANTHROPIC_AUTH_TOKEN is deliberately written as empty string: it neutralises a stale token
// inherited from an old parent process, which would otherwise silently disable auto-resume.
export const SETTINGS_ENV_KEYS = ['ANTHROPIC_BASE_URL', 'ANTHROPIC_CUSTOM_HEADERS', 'ANTHROPIC_AUTH_TOKEN'];

function settingsPath() {
  return path.join(CLAUDE_HOME, 'settings.json');
}

function settingsEnvWanted(cfg, legacy = false) {
  const base = `http://${cfg.host}:${cfg.port}`;
  if (legacy) return { ANTHROPIC_BASE_URL: base, ANTHROPIC_AUTH_TOKEN: cfg.secret, ANTHROPIC_CUSTOM_HEADERS: '' };
  return {
    ANTHROPIC_BASE_URL: base,
    ANTHROPIC_CUSTOM_HEADERS: `${cfg.secretHeader || SECRET_HEADER}: ${cfg.secret}`,
    ANTHROPIC_AUTH_TOKEN: '',
  };
}

// Touches only those three keys. Backs the file up once, and refuses rather than trashing a settings
// file that does not parse.
function applySettingsEnv(cfg, legacy = false) {
  const file = settingsPath();
  const wanted = settingsEnvWanted(cfg, legacy);
  let doc = {};
  if (fs.existsSync(file)) {
    const raw = fs.readFileSync(file, 'utf8');
    try { doc = JSON.parse(raw); }
    catch (e) { throw new Error(`${file} is not valid JSON (${e.message}) - refusing to touch it`); }
    if (!fs.existsSync(`${file}.claude-gw.bak`)) fs.writeFileSync(`${file}.claude-gw.bak`, raw);
  }
  doc.env = doc.env || {};
  const changed = [];
  for (const k of SETTINGS_ENV_KEYS) {
    if (doc.env[k] !== wanted[k]) { changed.push(k); doc.env[k] = wanted[k]; }
  }
  // Do not touch the file when it already agrees. Claude Code watches settings.json, and rewriting it
  // for no reason risks disturbing live sessions (a config change during a usage-limit wait is one of
  // the things that cancels that wait).
  if (!changed.length) return { changed, settingsPath: file, backup: `${file}.claude-gw.bak` };
  fs.writeFileSync(file, JSON.stringify(doc, null, 2));
  return { changed, settingsPath: file, backup: `${file}.claude-gw.bak` };
}

function settingsEnvState(cfg, legacy = false) {
  const file = settingsPath();
  try {
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    const env = doc.env || {};
    const wanted = settingsEnvWanted(cfg, legacy);
    const bad = SETTINGS_ENV_KEYS.filter((k) => (env[k] ?? '') !== (wanted[k] ?? ''));
    return { file, present: true, bad };
  } catch (e) { return { file, present: false, err: e.message }; }
}

function startupDir() {
  return ps("[Environment]::GetFolderPath('Startup')");
}
function startupCmdPath() { return path.join(startupDir(), 'claude-gw.cmd'); }

function installStartup() {
  const p = startupCmdPath();
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, [
    '@echo off',
    'rem claude-gw: start the local account gateway at logon. Remove this file to opt out.',
    `"${process.execPath}" "${path.join(HERE, 'cli.mjs')}" start >nul 2>&1`,
    '',
  ].join('\r\n'));
  return p;
}

function removeStartup() {
  const p = startupCmdPath();
  const existed = fs.existsSync(p);
  fs.rmSync(p, { force: true });
  return { p, existed };
}

async function gwStatus(cfg) {
  try {
    const r = await fetch(`http://${cfg.host}:${cfg.port}/__gw/status`, {
      headers: { authorization: `Bearer ${cfg.secret}` }, signal: AbortSignal.timeout(3000),
    });
    return r.ok ? await r.json() : null;
  } catch { return null; }
}
function fmtEpoch(ms) {
  if (!ms) return null;
  const d = new Date(ms);
  const hrs = Math.max(0, (ms - Date.now()) / 3.6e6);
  return `${d.toLocaleDateString()} ${d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })} (in ~${hrs.toFixed(1)}h)`;
}

// ---------------------------------------------------------------- activate

export async function activate({ noStartup = false, legacy = false } = {}) {
  const cfg = loadConfig();
  const base = `http://${cfg.host}:${cfg.port}`;
  console.log(`config:  ${CONFIG_PATH}`);
  console.log(`mode:    ${legacy ? 'LEGACY (ANTHROPIC_AUTH_TOKEN) - Claude Code will NOT auto-resume at a usage limit'
    : 'supported (secret in a header, no gateway credential) - Claude Code waits for the reset and continues by itself'}`);
  console.log(`pool:    ${pool(cfg).map((a) => a.label).join(', ') || '(EMPTY - nothing to route to)'}`);
  if (!pool(cfg).length) throw new Error('no enabled accounts; run: cla-gw add <label>');

  // In supported mode the client authenticates to US with its own claude.ai login, so that login has
  // to exist and be readable even though it is not in the rotation. Fail here rather than leaving
  // every Claude Code session on the machine unable to start.
  const login = resolveBearer({ kind: 'cli-credential' });
  if (!legacy) {
    if (login.err) throw new Error(`supported mode needs a signed-in Claude Code login and it is missing: ${login.err}`);
    const who = describeIdentity().identity;
    console.log(`login:   client credential ${who ? `${who.email} (${who.subscription || '?'})` : 'resolves'}${login.meta?.stale ? ' [access token stale - the CLI refreshes it]' : ''}`);
  }

  // Prove the credentials resolve BEFORE pointing the whole user's Claude traffic at us. This is the
  // difference between "broken later" and "refused now".
  for (const a of pool(cfg)) {
    const c = resolveBearer(a);
    const md = c.meta || {};
    const how = md.kind === 'vault' ? `vault setup-token, ~${md.expiresInDays}d left`
      : `CLI login${md.expiresInMin ? `, access token expires in ~${Math.max(1, Math.round(md.expiresInMin / 60))}h (CLI refreshes it)` : ''}`;
    if (c.err) throw new Error(`credential for "${a.label}" is not usable: ${c.err}`);
    console.log(`cred:    ${a.label} resolves (${how})`);
  }

  setUserVar('CLAUDE_CODE_USE_GATEWAY', '1');
  setUserVar('ANTHROPIC_BASE_URL', base);
  if (legacy) {
    setUserVar('ANTHROPIC_AUTH_TOKEN', cfg.secret);
    setUserVar('ANTHROPIC_CUSTOM_HEADERS', null);
  } else {
    setUserVar('ANTHROPIC_CUSTOM_HEADERS', `${SECRET_HEADER}: ${cfg.secret}`);
    // Its mere presence switches auto-resume off, so remove it even if it was set by something else.
    setUserVar('ANTHROPIC_AUTH_TOKEN', null);
  }
  console.log(`env:     ${(legacy ? LEGACY_VARS : GW_VARS).join(', ')} set at USER scope`);

  // ...and in Claude Code's own env block, which is what lets a long-running VS Code pick the mode up
  // on a Reload Window instead of needing a full quit.
  const se = applySettingsEnv(cfg, legacy);
  console.log(`settings: ${se.settingsPath} ${se.changed.length ? `env updated: ${se.changed.join(', ')} (backup: ${se.backup})` : 'env already current'}`);

  if (!noStartup) console.log(`startup: ${installStartup()}`);

  // Start it now so the vars are not pointing at a dead port.
  const before = await gwStatus(cfg);
  if (!before) {
    const child = spawn(process.execPath, [path.join(HERE, 'gw.mjs')],
      { detached: true, stdio: 'ignore', windowsHide: true });
    child.unref();
    await new Promise((r) => setTimeout(r, 1500));
  }
  const st = await gwStatus(cfg);
  console.log(`gateway: ${st ? `answering on ${base}` : 'NOT answering - check cla-gw status / the log'}`);

  const s = poolState();
  console.log(`\naccounts right now:\n${s}`);
  console.log(`
ACTIVATED. Two things you must do, in this order:
  1. Quit VS Code completely (not just close the window) and start it again.
     Already-running processes keep the old environment; that is the usual "it didn't work".
  2. Open a NEW terminal. This one still has no ANTHROPIC_BASE_URL.
Roll back with: cla-gw deactivate   (removes vars, startup entry, stops gateway)
Roll back to the OLD credential model (auto-resume off): cla-gw activate --legacy
Note: user-scope ANTHROPIC_BASE_URL affects every process you start, not just Claude Code.`);
}

export async function deactivate() {
  for (const v of ALL_VARS) setUserVar(v, null);
  // Take the env block out of Claude Code's settings too, otherwise the client keeps being pointed at
  // a port that is about to stop answering.
  try {
    const file = settingsPath();
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (doc.env) {
      for (const k of SETTINGS_ENV_KEYS) delete doc.env[k];
      fs.writeFileSync(file, JSON.stringify(doc, null, 2));
      console.log(`settings: gateway keys removed from ${file}`);
    }
  } catch (e) { console.log(`settings: could not clean ${settingsPath()} (${e.message}) - remove its ANTHROPIC_* env keys yourself`); }
  const r = removeStartup();
  spawnSync(process.execPath, [path.join(HERE, 'cli.mjs'), 'stop'], { stdio: 'ignore' });
  console.log(`env:     ${ALL_VARS.join(', ')} removed from USER scope`);
  console.log(`startup: ${r.existed ? `removed ${r.p}` : 'no startup entry was installed'}`);
  console.log('gateway stopped. Running VS Code / terminals keep their OLD env until restarted.');
}

function poolState() {
  const cfg = loadConfig();
  const state = readAccountState();
  const now = Date.now();
  const lines = [];
  for (const a of pool(cfg)) {
    const st = state[a.label] || {};
    const av = availability(st, now);
    lines.push(av.readyAt > now
      ? `  ${a.label}: RESTRICTED until ${fmtEpoch(av.readyAt)}`
      : `  ${a.label}: available${st.u7d !== undefined ? ` (7d ${Math.round((st.u7d || 0) * 100)}%)` : ''}`);
  }
  const blocked = lines.filter((l) => l.includes('RESTRICTED'));
  if (blocked.length === lines.length && lines.length) {
    const when = Math.min(...pool(cfg).map((a) => availability(state[a.label] || {}, now).readyAt).filter(Boolean));
    lines.push(`  ALL RESTRICTED - next capacity frees ${fmtEpoch(when)}`);
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------- doctor

export async function doctor() {
  const cfg = loadConfig();
  const base = `http://${cfg.host}:${cfg.port}`;
  const problems = [];
  const say = (ok, label, detail) => {
    console.log(`${ok ? 'ok  ' : 'FIX '} ${label}${detail ? `  - ${detail}` : ''}`);
    if (!ok) problems.push(label);
  };

  say(fs.existsSync(CONFIG_PATH), 'config exists', CONFIG_PATH);
  const p = pool(cfg);
  say(p.length > 0, 'at least one enabled account', p.map((a) => `${a.label}${a.enabled === false ? '(off)' : ''}`).join(', ') || 'none');
  for (const a of p) {
    const c = resolveBearer(a);
    const md = c.meta || {};
    const how = md.kind === 'vault' ? `vault setup-token, ~${md.expiresInDays}d left`
      : `CLI login (${md.subscriptionType || '?'}), access token expires in ~${Math.max(1, Math.round((md.expiresInMin || 0) / 60))}h and the CLI refreshes it`;
    say(!c.err, `credential for ${a.label} resolves`, c.err || how);
  }

  const upstreamIsReal = !/^http:\/\/(127|localhost)/.test(cfg.upstream);
  say(upstreamIsReal, 'upstream is the real API', cfg.upstream + (upstreamIsReal ? '' : '  <-- a test left this pointing at a fake server; every real request will fail'));

  const got = {
    CLAUDE_CODE_USE_GATEWAY: readUserVar('CLAUDE_CODE_USE_GATEWAY'),
    ANTHROPIC_BASE_URL: readUserVar('ANTHROPIC_BASE_URL'),
    ANTHROPIC_CUSTOM_HEADERS: readUserVar('ANTHROPIC_CUSTOM_HEADERS'),
    ANTHROPIC_AUTH_TOKEN: readUserVar('ANTHROPIC_AUTH_TOKEN'),
  };
  const wantHdr = `${SECRET_HEADER}: ${cfg.secret}`;
  const supported = got.ANTHROPIC_CUSTOM_HEADERS === wantHdr;
  const legacy = !!got.ANTHROPIC_AUTH_TOKEN && got.ANTHROPIC_AUTH_TOKEN === cfg.secret;
  say(got.CLAUDE_CODE_USE_GATEWAY === '1', 'CLAUDE_CODE_USE_GATEWAY set', String(got.CLAUDE_CODE_USE_GATEWAY));
  say(got.ANTHROPIC_BASE_URL === base, 'env base URL points at the gateway', `${got.ANTHROPIC_BASE_URL} vs ${base}`);
  say(supported || legacy, 'gateway credential reaches the gateway',
    supported ? `mode: supported (${SECRET_HEADER} header agrees)`
      : legacy ? 'mode: LEGACY (bearer secret) - works, but auto-resume at the usage limit is OFF; run: cla-gw activate'
        : `neither ${SECRET_HEADER} nor a matching ANTHROPIC_AUTH_TOKEN is in the env - run: cla-gw activate`);
  if (supported) {
    say(!got.ANTHROPIC_AUTH_TOKEN, 'ANTHROPIC_AUTH_TOKEN is absent',
      got.ANTHROPIC_AUTH_TOKEN ? 'PRESENT: Claude Code treats this machine as a billed-API session and '
        + 'silently disables "continue automatically at usage limit" - run: cla-gw activate'
        : 'absent, so the session keeps its claude.ai subscription mode');
    // The client authenticates to us with its own login in supported mode.
    const login = resolveBearer({ kind: 'cli-credential' });
    const who = describeIdentity().identity;
    say(!login.err, 'client login usable (authenticates to the gateway)',
      login.err ? `${login.err}${login.hint ? ` - ${login.hint}` : ''}` : `${who?.email || '?'}, access token ${login.meta?.stale ? 'STALE (CLI refreshes it)' : `ok, ~${Math.max(1, Math.round((login.meta?.expiresInMin || 0) / 60))} min left`}`);
  }

  // The env block inside Claude Code's own settings is what makes a long-running VS Code/terminal get
  // the right mode without a restart, and what keeps a stale ANTHROPIC_AUTH_TOKEN from re-appearing.
  const ses = settingsEnvState(cfg, legacy);
  say(ses.present && !ses.bad.length, 'gateway keys present in Claude Code settings env',
    ses.present ? (ses.bad.length ? `stale/missing: ${ses.bad.join(', ')} - run: cla-gw activate` : `agree (${ses.file})`)
      : `cannot use ${ses.file} (${ses.err})`);

  const st = await gwStatus(cfg);
  const pid = fs.existsSync(PID_PATH) ? fs.readFileSync(PID_PATH, 'utf8').trim() : '?';
  say(!!st, 'gateway answering', st ? `pid ${pid}, uptime ${(st.uptimeMs / 1000).toFixed(0)}s, requests ${st.stats?.requests}` : `nothing on ${base} - run: cla-gw start`);
  if (fs.existsSync(PID_PATH) && !st) say(false, 'pid file is stale', `${PID_PATH} exists but the port is silent (process died?)`);

  const sp = startupCmdPath();
  say(fs.existsSync(sp), 'gateway starts at logon', sp);

  // Informational, not a fault: the CLI process invoking doctor legitimately may not carry the vars.
  console.log(`info: this process ${process.env.ANTHROPIC_BASE_URL ? `sees ANTHROPIC_BASE_URL=${process.env.ANTHROPIC_BASE_URL}` : 'has no ANTHROPIC_BASE_URL (a shell opened after activating will)'}`);

  const s = poolState();
  console.log(`\naccount capacity right now:\n${s}`);
  const home = process.env.USERPROFILE || process.env.HOME || '';
  const loginFiles = [path.join(home, '.claude.json'), path.join(CLAUDE_HOME, '.claude.json')];
  const cliHome = loginFiles.find((f) => fs.existsSync(f));
  say(!!cliHome, 'CLI login file present', cliHome || `${loginFiles.join(' or ')} not found - account A cannot authenticate`);

  console.log(`\nverdict: ${problems.length ? `${problems.length} thing(s) to fix:\n  - ${problems.join('\n  - ')}` : 'healthy'}`);
  console.log(`log: ${LOG_PATH}`);
  return problems.length === 0;
}

// ---------------------------------------------------------------- one-off bypass

export function runWithoutGateway(argv) {
  // For the "I want the real account A directly, right now" case. Deleting the vars from the child's
  // environment is enough; nothing persistent is touched.
  const env = { ...process.env };
  for (const v of ALL_VARS) delete env[v];
  const r = spawnSync('claude', argv, { stdio: 'inherit', env });
  process.exit(r.status ?? 0);
}
