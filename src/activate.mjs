// Phase 5: make the gateway the thing Claude Code actually talks to, and make it reversible.
//
// D-6 is the whole design: real *user-scope* environment variables, because the VS Code extension
// runs its own bundled claude.exe (useTerminal defaults to false) and a shell alias would cover the
// terminal but not the extension. User-scope vars cover both.
//
// The cost of that choice, stated plainly:
//   * ANTHROPIC_BASE_URL at user scope affects EVERY process this user starts, not just Claude
//     Code. Any other Anthropic SDK script on this machine will route through the gateway too.
//   * If the gateway is not running, Claude Code cannot reach the API at all. So activation also
//     installs a logon startup entry, and `doctor` is the first thing to reach for when anything
//     looks broken.
//   * Already-running processes (VS Code, terminals) keep the OLD environment. Activation prints
//     that reminder because it is the #1 "it didn't work" cause.

import { execFileSync, spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
import { loadConfig, pool, readAccountState, availability, CONFIG_PATH, PID_PATH, LOG_PATH } from './config.mjs';
import { resolveBearer, describeIdentity } from './creds.mjs';

const CLAUDE_HOME = process.env.CLAUDE_CONFIG_DIR || path.join(process.env.USERPROFILE || process.env.HOME || '', '.claude');

export const GW_VARS = ['CLAUDE_CODE_USE_GATEWAY', 'ANTHROPIC_BASE_URL', 'ANTHROPIC_AUTH_TOKEN'];

function ps(script) {
  // PowerShell 5.1, no profile. Values passed in are generated by us (hex secret, loopback URL) and
  // validated by setUserVar's guard, so inlining them is safe; secrets never travel in argv here
  // because these names/values are not sensitive beyond the local gateway secret.
  return execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 30000 }).trim();
}

export function readUserVar(name) {
  try { return ps(`[Environment]::GetEnvironmentVariable('${name}','User')`) || null; } catch { return null; }
}

export function setUserVar(name, value) {
  if (value !== null && !/^[\w:/.\-]+$/.test(String(value))) {
    throw new Error(`refusing to write suspicious env value for ${name}`);
  }
  const v = value === null ? '$null' : `'${value}'`;
  ps(`[Environment]::SetEnvironmentVariable('${name}', ${v}, 'User')`);
}

function startupDir() {
  return ps("[Environment]::GetFolderPath('Startup')");
}
function startupCmdPath() { return path.join(startupDir(), 'claude-gw.cmd'); }

function installStartup() {
  const p = startupCmdPath();
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, [
    '@echo off',
    'rem claude-gw: start the local account gateway at logon. Remove this file to opt out.',
    `"${process.execPath}" "${path.join(HERE, 'cli.mjs')}" start >nul 2>&1`,
    '',
  ].join('\r\n'));
  return p;
}

function removeStartup() {
  const p = startupCmdPath();
  const existed = fs.existsSync(p);
  fs.rmSync(p, { force: true });
  return { p, existed };
}

async function gwStatus(cfg) {
  try {
    const r = await fetch(`http://${cfg.host}:${cfg.port}/__gw/status`, {
      headers: { authorization: `Bearer ${cfg.secret}` }, signal: AbortSignal.timeout(3000),
    });
    return r.ok ? await r.json() : null;
  } catch { return null; }
}

function fmtEpoch(ms) {
  if (!ms) return null;
  const d = new Date(ms);
  const hrs = Math.max(0, (ms - Date.now()) / 3.6e6);
  return `${d.toLocaleDateString()} ${d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })} (in ~${hrs.toFixed(1)}h)`;
}

// ---------------------------------------------------------------- activate

export async function activate({ noStartup = false } = {}) {
  const cfg = loadConfig();
  const base = `http://${cfg.host}:${cfg.port}`;
  console.log(`config:  ${CONFIG_PATH}`);
  console.log(`pool:    ${pool(cfg).map((a) => a.label).join(', ') || '(EMPTY - nothing to route to)'}`);
  if (!pool(cfg).length) throw new Error('no enabled accounts; run: cla-gw add <label>');

  // Prove the credentials resolve BEFORE pointing the whole user's Claude traffic at us. This is the
  // difference between "broken later" and "refused now".
  for (const a of pool(cfg)) {
    const c = resolveBearer(a);
    const md = c.meta || {};
    const how = md.kind === 'vault' ? `vault setup-token, ~${md.expiresInDays}d left`
      : `CLI login${md.expiresInMin ? `, access token expires in ~${Math.max(1, Math.round(md.expiresInMin / 60))}h (CLI refreshes it)` : ''}`;
    if (c.err) throw new Error(`credential for "${a.label}" is not usable: ${c.err}`);
    console.log(`cred:    ${a.label} resolves (${how})`);
  }

  setUserVar('CLAUDE_CODE_USE_GATEWAY', '1');
  setUserVar('ANTHROPIC_BASE_URL', base);
  setUserVar('ANTHROPIC_AUTH_TOKEN', cfg.secret);
  console.log(`env:     ${GW_VARS.join(', ')} set at USER scope`);

  if (!noStartup) console.log(`startup: ${installStartup()}`);

  // Start it now so the vars are not pointing at a dead port.
  const before = await gwStatus(cfg);
  if (!before) {
    const child = spawn(process.execPath, [path.join(HERE, 'gw.mjs')],
      { detached: true, stdio: 'ignore', windowsHide: true });
    child.unref();
    await new Promise((r) => setTimeout(r, 1500));
  }
  const st = await gwStatus(cfg);
  console.log(`gateway: ${st ? `answering on ${base}` : 'NOT answering - check cla-gw status / the log'}`);

  const s = poolState();
  console.log(`\naccounts right now:\n${s}`);
  console.log(`
ACTIVATED. Two things you must do, in this order:
  1. Quit VS Code completely (not just close the window) and start it again.
     Already-running processes keep the old environment; that is the usual "it didn't work".
  2. Open a NEW terminal. This one still has no ANTHROPIC_BASE_URL.
Roll back with: cla-gw deactivate   (removes vars, startup entry, stops gateway)
Note: user-scope ANTHROPIC_BASE_URL affects every process you start, not just Claude Code.`);
}

export async function deactivate() {
  for (const v of GW_VARS) setUserVar(v, null);
  const r = removeStartup();
  spawnSync(process.execPath, [path.join(HERE, 'cli.mjs'), 'stop'], { stdio: 'ignore' });
  console.log(`env:     ${GW_VARS.join(', ')} removed from USER scope`);
  console.log(`startup: ${r.existed ? `removed ${r.p}` : 'no startup entry was installed'}`);
  console.log('gateway stopped. Running VS Code / terminals keep their OLD env until restarted.');
}

function poolState() {
  const cfg = loadConfig();
  const state = readAccountState();
  const now = Date.now();
  const lines = [];
  for (const a of pool(cfg)) {
    const st = state[a.label] || {};
    const av = availability(st, now);
    lines.push(av.readyAt > now
      ? `  ${a.label}: RESTRICTED until ${fmtEpoch(av.readyAt)}`
      : `  ${a.label}: available${st.u7d !== undefined ? ` (7d ${Math.round((st.u7d || 0) * 100)}%)` : ''}`);
  }
  const blocked = lines.filter((l) => l.includes('RESTRICTED'));
  if (blocked.length === lines.length && lines.length) {
    const when = Math.min(...pool(cfg).map((a) => availability(state[a.label] || {}, now).readyAt).filter(Boolean));
    lines.push(`  ALL RESTRICTED - next capacity frees ${fmtEpoch(when)}`);
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------- doctor

export async function doctor() {
  const cfg = loadConfig();
  const base = `http://${cfg.host}:${cfg.port}`;
  const problems = [];
  const say = (ok, label, detail) => {
    console.log(`${ok ? 'ok  ' : 'FIX '} ${label}${detail ? `  - ${detail}` : ''}`);
    if (!ok) problems.push(label);
  };

  say(fs.existsSync(CONFIG_PATH), 'config exists', CONFIG_PATH);
  const p = pool(cfg);
  say(p.length > 0, 'at least one enabled account', p.map((a) => `${a.label}${a.enabled === false ? '(off)' : ''}`).join(', ') || 'none');
  for (const a of p) {
    const c = resolveBearer(a);
    const md = c.meta || {};
    const how = md.kind === 'vault' ? `vault setup-token, ~${md.expiresInDays}d left`
      : `CLI login (${md.subscriptionType || '?'}), access token expires in ~${Math.max(1, Math.round((md.expiresInMin || 0) / 60))}h and the CLI refreshes it`;
    say(!c.err, `credential for ${a.label} resolves`, c.err || how);
  }

  const upstreamIsReal = !/^http:\/\/(127|localhost)/.test(cfg.upstream);
  say(upstreamIsReal, 'upstream is the real API', cfg.upstream + (upstreamIsReal ? '' : '  <-- a test left this pointing at a fake server; every real request will fail'));

  const got = {
    CLAUDE_CODE_USE_GATEWAY: readUserVar('CLAUDE_CODE_USE_GATEWAY'),
    ANTHROPIC_BASE_URL: readUserVar('ANTHROPIC_BASE_URL'),
    ANTHROPIC_AUTH_TOKEN: readUserVar('ANTHROPIC_AUTH_TOKEN'),
  };
  const active = GW_VARS.every((v) => got[v]);
  say(active, 'user-scope env vars are set', GW_VARS.map((v) => `${v}=${got[v] ? (v === 'ANTHROPIC_AUTH_TOKEN' ? '<set>' : got[v]) : 'MISSING'}`).join(' '));
  if (active) {
    say(got.ANTHROPIC_BASE_URL === base, 'env base URL matches config', `${got.ANTHROPIC_BASE_URL} vs ${base}`);
    say(got.ANTHROPIC_AUTH_TOKEN === cfg.secret, 'env secret matches gateway',
      got.ANTHROPIC_AUTH_TOKEN === cfg.secret ? 'shared secret agrees' : 'STALE: gateway would answer 401 - run cla-gw activate again');
  }

  const st = await gwStatus(cfg);
  const pid = fs.existsSync(PID_PATH) ? fs.readFileSync(PID_PATH, 'utf8').trim() : '?';
  say(!!st, 'gateway answering', st ? `pid ${pid}, uptime ${(st.uptimeMs / 1000).toFixed(0)}s, requests ${st.stats?.requests}` : `nothing on ${base} - run: cla-gw start`);
  if (fs.existsSync(PID_PATH) && !st) say(false, 'pid file is stale', `${PID_PATH} exists but the port is silent (process died?)`);

  const sp = startupCmdPath();
  say(fs.existsSync(sp), 'gateway starts at logon', sp);

  // Informational, not a fault: the CLI process invoking doctor legitimately may not carry the vars.
  console.log(`info: this process ${process.env.ANTHROPIC_BASE_URL ? `sees ANTHROPIC_BASE_URL=${process.env.ANTHROPIC_BASE_URL}` : 'has no ANTHROPIC_BASE_URL (a shell opened after activating will)'}`);

  const s = poolState();
  console.log(`\naccount capacity right now:\n${s}`);
  const home = process.env.USERPROFILE || process.env.HOME || '';
  const loginFiles = [path.join(home, '.claude.json'), path.join(CLAUDE_HOME, '.claude.json')];
  const cliHome = loginFiles.find((f) => fs.existsSync(f));
  say(!!cliHome, 'CLI login file present', cliHome || `${loginFiles.join(' or ')} not found - account A cannot authenticate`);

  console.log(`\nverdict: ${problems.length ? `${problems.length} thing(s) to fix:\n  - ${problems.join('\n  - ')}` : 'healthy'}`);
  console.log(`log: ${LOG_PATH}`);
  return problems.length === 0;
}

// ---------------------------------------------------------------- one-off bypass

export function runWithoutGateway(argv) {
  // For the "I want the real account A directly, right now" case. Deleting the vars from the child's
  // environment is enough; nothing persistent is touched.
  const env = { ...process.env };
  for (const v of GW_VARS) delete env[v];
  const r = spawnSync('claude', argv, { stdio: 'inherit', env });
  process.exit(r.status ?? 0);
}
